#!/usr/bin/env python3
"""Generate native and browser presentation defaults from the example manifest."""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path

import gallery_media


ROOT = gallery_media.ROOT
KINDS = {"default": 0, "static": 1, "sway": 2}


def presentation(entry: dict, profile: str = "") -> dict:
    """Normalize the presentation consumed by capture, native, and browser runners."""
    resolved = gallery_media.resolve_media_entry(entry, profile)
    preview = gallery_media.preview_metadata(resolved)
    values = preview.get("presentation", {})
    if not isinstance(values, dict) or set(values) - {"kind", "amplitude_deg", "period_seconds"}:
        raise ValueError(f"{entry['id']}: invalid presentation fields")
    kind = values.get("kind", "default")
    if kind not in KINDS:
        raise ValueError(f"{entry['id']}: unknown presentation kind {kind!r}")
    duration = float(preview.get("frames", 864)) / float(preview.get("fps", 60))
    period = float(values.get("period_seconds", duration))
    amplitude = float(values.get("amplitude_deg", 0))
    if (not math.isfinite(amplitude) or not math.isfinite(period) or
            not 0 <= amplitude <= 180 or not 0 < period < 86400):
        raise ValueError(f"{entry['id']}: invalid presentation amplitude or period")
    return {"profile": profile or "default", "kind": kind,
            "amplitudeDeg": amplitude, "periodSeconds": period}


def live_profiles(manifest: dict) -> dict:
    """Resolve only explicit shared defaults; absent entries retain interactive behavior."""
    profiles = {}
    for entry in manifest.get("examples", []):
        scenario = entry.get("scenario", {})
        if not isinstance(scenario, dict) or set(scenario) - {"presentation_profile"}:
            raise ValueError(f"{entry['id']}: unknown scenario configuration")
        profile = scenario.get("presentation_profile")
        if profile:
            profiles[entry["id"]] = presentation(entry, profile)
    return profiles


def generated_files(manifest: dict) -> dict[Path, str]:
    profiles = live_profiles(manifest)
    encoded = json.dumps(profiles, sort_keys=True, separators=(",", ":"))
    identity = hashlib.sha256(encoded.encode()).hexdigest()
    js = "// Generated by tools/example_profiles.py; edit examples/c/MANIFEST.yaml.\n"
    js += f'export const PRESENTATION_VERSION = "sha256-{identity}";\n'
    js += "export const LIVE_PRESENTATION_PROFILES = " + json.dumps(profiles, indent=2, sort_keys=True) + ";\n"
    header = "/* Generated by tools/example_profiles.py; edit examples/c/MANIFEST.yaml. */\n#pragma once\n\n"
    header += f'#define EXAMPLE_PRESENTATION_VERSION "sha256-{identity}"\n'
    header += "static const ScenarioPresentationEntry scenario_presentation_entries[] = {\n"
    for id_, values in sorted(profiles.items()):
        header += '    {%s, {%d, %.17g, %.17g}},\n' % (json.dumps(id_), KINDS[values["kind"]], values["amplitudeDeg"], values["periodSeconds"])
    header += "    {NULL, {0, 0, 0}},\n};\n"
    return {ROOT / "examples/webgpu/live_profiles.js": js, ROOT / "examples/c/runner/scenario_profiles.h": header}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generated_files(gallery_media.load_manifest(gallery_media.DEFAULT_MANIFEST)).items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f"stale generated presentation defaults: {path.relative_to(ROOT)}")
        else:
            path.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
