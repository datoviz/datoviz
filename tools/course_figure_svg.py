"""Small SVG helpers for the course's authored, theme-aware schematics."""

from html import escape

COLORS = {
    'ink': 'var(--md-default-fg-color, #253247)',
    'muted': 'var(--md-default-fg-color--light, #586579)',
    'line': 'var(--md-default-fg-color--lighter, #8593a6)',
    'paper': 'var(--md-code-bg-color, #f5f7fa)',
    'blue': 'var(--dvz-blue, #1766a4)',
    'orange': 'var(--dvz-orange, #985511)',
    'green': 'var(--dvz-green, #23745a)',
    'red': 'var(--dvz-red, #a63e4a)',
    'purple': 'var(--dvz-purple, #7952b0)',
}


def color(value):
    """Resolve a diagram color name or keep a literal SVG color."""
    return COLORS.get(value, value)


class SVG:
    """Build an accessible SVG panel with a deterministic text representation."""

    def __init__(self, name, title, description, width=320, height=300):
        """Initialize the panel, accessible title, description and background."""
        self.name, self.width, self.height = name, width, height
        self.parts = [
            f'<svg xmlns="http://www.w3.org/2000/svg" class="dvz-schematic" '
            f'viewBox="0 0 {width} {height}" role="img" '
            f'aria-labelledby="{name}-title {name}-desc">',
            f'<title id="{name}-title">{escape(title)}</title>',
            f'<desc id="{name}-desc">{escape(description)}</desc>',
            '<g font-family="system-ui, sans-serif" font-size="14">',
        ]
        self.rect(0, 0, width, height, 'paper', stroke='none', radius=4)

    def raw(self, markup):
        """Append trusted SVG markup generated by the figure builders."""
        self.parts.append(markup)

    def text(self, x, y, text, size=14, fill='ink', anchor='start', bold=False):
        """Draw an escaped text label at the given baseline."""
        weight = ' font-weight="600"' if bold else ''
        self.raw(
            f'<text x="{x:g}" y="{y:g}" font-size="{size}" fill="{color(fill)}" '
            f'text-anchor="{anchor}"{weight}>{escape(str(text))}</text>'
        )

    def line(self, x1, y1, x2, y2, stroke='line', width=1.5, dash=False):
        """Draw a solid or dashed line between two points."""
        extra = ' stroke-dasharray="5 4"' if dash else ''
        self.raw(
            f'<line x1="{x1:g}" y1="{y1:g}" x2="{x2:g}" y2="{y2:g}" '
            f'stroke="{color(stroke)}" stroke-width="{width}"{extra}/>'
        )

    def arrow(self, x1, y1, x2, y2, stroke='ink', width=2):
        """Draw a line with a filled arrowhead at its endpoint."""
        from math import atan2, cos, sin

        self.line(x1, y1, x2, y2, stroke, width)
        a = atan2(y2 - y1, x2 - x1)
        points = [
            (x2, y2),
            (x2 - 8 * cos(a - 0.45), y2 - 8 * sin(a - 0.45)),
            (x2 - 8 * cos(a + 0.45), y2 - 8 * sin(a + 0.45)),
        ]
        self.polygon(points, stroke)

    def rect(self, x, y, width, height, fill='paper', stroke='line', radius=0):
        """Draw a rectangle, optionally with rounded corners."""
        self.raw(
            f'<rect x="{x:g}" y="{y:g}" width="{width:g}" height="{height:g}" '
            f'rx="{radius}" fill="{color(fill)}" stroke="{color(stroke)}"/>'
        )

    def circle(self, x, y, radius, fill='ink', stroke='none'):
        """Draw a circle with the requested fill and outline."""
        self.raw(
            f'<circle cx="{x:g}" cy="{y:g}" r="{radius:g}" fill="{color(fill)}" '
            f'stroke="{color(stroke)}"/>'
        )

    def polygon(self, points, fill='blue', stroke='none', opacity=1):
        """Draw a polygon from its ordered vertex coordinates."""
        data = ' '.join(f'{x:g},{y:g}' for x, y in points)
        self.raw(
            f'<polygon points="{data}" fill="{color(fill)}" stroke="{color(stroke)}" '
            f'fill-opacity="{opacity}"/>'
        )

    def finish(self):
        """Close the SVG and return its complete source text."""
        return '\n'.join(self.parts + ['</g>', '</svg>', ''])
