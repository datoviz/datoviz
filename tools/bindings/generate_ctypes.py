def _candidate_library_paths():
    env_path = os.environ.get('DATOVIZ_LIBRARY')
    if env_path:
        yield pathlib.Path(env_path)

    names = _PLATFORM_LIB_NAMES.get(platform.system())
    if not names:
        return

    here = pathlib.Path(__file__).resolve().parent
    root = here.parent
    for name in names:
        yield here / name
        yield root / 'build' / 'src' / name
        yield root / 'build' / name

    # Conda installs Python modules under <prefix>/lib/pythonX.Y/site-packages and native
    # libraries under <prefix>/lib on Unix or <prefix>/Library/bin on Windows.
    for parent in here.parents:
        for name in names:
            yield parent / 'lib' / name
            yield parent / 'Library' / 'bin' / name


def _configure_runtime_dirs():
    here = pathlib.Path(__file__).resolve().parent
    existing = [
        path
        for path in os.environ.get('DVZ_WHEEL_RUNTIME_DIRS', '').split(os.pathsep)
        if path
    ]
    here_str = str(here)
    dirs = [here_str, *[path for path in existing if path != here_str]]
    os.environ['DVZ_WHEEL_RUNTIME_DIRS'] = os.pathsep.join(dirs)
    if platform.system() == 'Windows' and hasattr(os, 'add_dll_directory'):
        os.add_dll_directory(here_str)


def _load_library():
    _configure_runtime_dirs()
    errors = []
    missing = []
    for path in _candidate_library_paths():
        if not path.exists():
            missing.append(str(path))
            continue
        try:
            return ctypes.cdll.LoadLibrary(str(path))
        except OSError as exc:
            errors.append(f'{path}: {exc}')
    loader_env_names = ('LD_LIBRARY_PATH', 'DYLD_LIBRARY_PATH', 'PATH')
    loader_env = ', '.join(
        f'{name}={os.environ.get(name, "")!r}' for name in loader_env_names
    )
    context = (
        f'platform={platform.system()!r}; '
        f'DATOVIZ_LIBRARY={os.environ.get("DATOVIZ_LIBRARY", "")!r}; '
        f'{loader_env}'
    )
    details = []
    if errors:
        details.append('load errors: ' + '; '.join(errors))
    if missing:
        details.append('missing candidates: ' + ', '.join(missing))
    if not details:
        details.append('no candidate path was generated')
    raise RuntimeError(f'Unable to load libdatoviz ({context}; {"; ".join(details)})')


