#!/usr/bin/env python3
"""Generate the raw Datoviz ctypes module from extracted API JSON."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


ROOT_DIR = Path(__file__).resolve().parents[2]
DEFAULT_INPUT = ROOT_DIR / 'build' / 'bindings' / 'datoviz_api.json'
DEFAULT_OUTPUT = ROOT_DIR / 'datoviz' / '_ctypes.py'

HEADER = '''\
"""
Raw ctypes bindings for Datoviz v0.4.

This file is generated by tools/bindings/generate_ctypes.py. Do not edit it by hand.
"""

from __future__ import annotations

import ctypes
import os
import pathlib
import platform
from enum import IntEnum


class CtypesEnum(IntEnum):
    @classmethod
    def from_param(cls, obj):
        return int(obj)


_PLATFORM_LIB_NAMES = {
    'Linux': 'libdatoviz.so',
    'Darwin': 'libdatoviz.dylib',
    'Windows': 'libdatoviz.dll',
}


def _candidate_library_paths():
    env_path = os.environ.get('DATOVIZ_LIBRARY')
    if env_path:
        yield pathlib.Path(env_path)

    name = _PLATFORM_LIB_NAMES.get(platform.system())
    if not name:
        return

    here = pathlib.Path(__file__).resolve().parent
    root = here.parent
    yield here / name
    yield root / 'build' / 'src' / name
    yield root / 'build' / name


def _load_library():
    errors = []
    for path in _candidate_library_paths():
        if not path.exists():
            continue
        try:
            return ctypes.cdll.LoadLibrary(str(path))
        except OSError as exc:
            errors.append(f'{path}: {exc}')
    details = '; '.join(errors) if errors else 'no candidate file exists'
    raise RuntimeError(f'Unable to load libdatoviz ({details})')


dvz = _load_library()
_MISSING_FUNCTIONS = []
_DATOVIZ_CTYPES_LAYOUT_RECORDS = []

'''

CTYPE_MAP = {
    'void': 'None',
    'bool': 'ctypes.c_bool',
    '_Bool': 'ctypes.c_bool',
    'char': 'ctypes.c_char',
    'signed char': 'ctypes.c_int8',
    'unsigned char': 'ctypes.c_uint8',
    'int8_t': 'ctypes.c_int8',
    'uint8_t': 'ctypes.c_uint8',
    'int16_t': 'ctypes.c_int16',
    'uint16_t': 'ctypes.c_uint16',
    'int32_t': 'ctypes.c_int32',
    'uint32_t': 'ctypes.c_uint32',
    'int64_t': 'ctypes.c_int64',
    'uint64_t': 'ctypes.c_uint64',
    'int': 'ctypes.c_int',
    'unsigned int': 'ctypes.c_uint',
    'long': 'ctypes.c_long',
    'unsigned long': 'ctypes.c_ulong',
    'long long': 'ctypes.c_longlong',
    'unsigned long long': 'ctypes.c_ulonglong',
    'size_t': 'ctypes.c_size_t',
    'ssize_t': 'ctypes.c_ssize_t',
    'float': 'ctypes.c_float',
    'double': 'ctypes.c_double',
    'DvzId': 'ctypes.c_uint64',
    'DvzSize': 'ctypes.c_uint64',
}


ARRAY_RE = re.compile(r'^(?P<base>.+?)(?P<dims>(?:\[[0-9]+\])+)$')
DIM_RE = re.compile(r'\[([0-9]+)\]')


def _clean_type(qualtype: str) -> str:
    out = ' '.join(qualtype.replace(' *', '*').replace('*', ' * ').split())
    return ' '.join(token for token in out.split() if token != 'const')


def _array_ctype(
    qualtype: str, records: set[str], enums: set[str], value_records: set[str] | None = None
) -> str | None:
    match = ARRAY_RE.match(_clean_type(qualtype))
    if not match:
        return None
    ctype = _ctype_for(match.group('base').strip(), records, enums, value_records=value_records)
    if ctype is None:
        return None
    for dim in reversed([int(dim) for dim in DIM_RE.findall(match.group('dims'))]):
        ctype = f'({ctype} * {dim})'
    return ctype


def _pointer_ctype(qualtype: str, records: set[str], enums: set[str]) -> str | None:
    t = _clean_type(qualtype)
    if '*' not in t:
        return None
    if '(*' in qualtype:
        return 'ctypes.c_void_p'

    depth = t.count('*')
    target = t.replace('*', ' ').strip()
    if target.startswith('struct '):
        target = target[len('struct ') :]
    if target.startswith('enum '):
        target = target[len('enum ') :]

    if target == 'char' and depth == 1:
        return 'ctypes.c_char_p'
    if target == 'char' and depth == 2:
        return 'ctypes.POINTER(ctypes.c_char_p)'
    if target == 'void' and depth == 1:
        return 'ctypes.c_void_p'
    if target in records:
        base = target
        for _ in range(depth):
            base = f'ctypes.POINTER({base})'
        return base

    base = _ctype_for(target, records, enums)
    if base is None:
        return 'ctypes.c_void_p'
    for _ in range(depth):
        base = f'ctypes.POINTER({base})'
    return base


def _ctype_for_type(
    type_info: dict,
    records: set[str],
    enums: set[str],
    value_records: set[str] | None = None,
) -> str | None:
    for spelling in (type_info.get('qualtype', ''), type_info.get('canonical', '')):
        ctype = _array_ctype(spelling, records, enums, value_records=value_records)
        if ctype is not None:
            return ctype
    return _ctype_for(type_info.get('qualtype', ''), records, enums, value_records=value_records)


def _unsupported_field_layout(type_info: dict) -> bool:
    for spelling in (type_info.get('qualtype', ''), type_info.get('canonical', '')):
        t = _clean_type(spelling)
        if t.startswith(('vec', 'dvec', 'mat')):
            return True
        if ('float[' in t or 'double[' in t) and '*' not in t:
            return True
    return False


def _record_dependency(type_info: dict, records: set[str]) -> str | None:
    for spelling in (type_info.get('qualtype', ''), type_info.get('canonical', '')):
        t = _clean_type(spelling)
        if '*' in t:
            continue
        match = ARRAY_RE.match(t)
        if match:
            t = match.group('base').strip()
        if t.startswith('struct '):
            t = t[len('struct ') :]
        if t in records:
            return t
    return None


def _ordered_records(api: dict, records: set[str]) -> list[dict]:
    by_name = {record['name']: record for record in api.get('records', []) if record.get('name')}
    visiting: set[str] = set()
    visited: set[str] = set()
    ordered: list[dict] = []

    def visit(name: str) -> None:
        if name in visited or name in visiting:
            return
        record = by_name.get(name)
        if record is None:
            return
        visiting.add(name)
        if not record.get('opaque'):
            for field in record.get('fields', []):
                dep = _record_dependency(field.get('type', {}), records)
                if dep and dep != name:
                    visit(dep)
        visiting.remove(name)
        visited.add(name)
        ordered.append(record)

    for name in sorted(by_name):
        visit(name)
    return ordered


def _layoutable_records(ordered_records: list[dict], records: set[str], enums: set[str]) -> set[str]:
    out: set[str] = set()
    for record in ordered_records:
        name = record.get('name')
        if not name or record.get('opaque'):
            continue
        for field in record.get('fields', []):
            field_name = field.get('name')
            if not field_name or _unsupported_field_layout(field.get('type', {})):
                break
            dep = _record_dependency(field.get('type', {}), records)
            if dep and dep not in out:
                break
            ctype = _ctype_for_type(field.get('type', {}), records, enums, value_records=out)
            if ctype is None:
                break
        else:
            out.add(name)
    return out


def _class_name_for_pointer(qualtype: str, records: set[str]) -> str | None:
    t = _clean_type(qualtype)
    if not t.endswith('*'):
        return None
    target = t[:-1].strip()
    if target.startswith('struct '):
        target = target[len('struct ') :]
    if target.startswith('enum '):
        target = target[len('enum ') :]
    if target in records:
        return target
    return None


def _ctype_for(
    qualtype: str,
    records: set[str],
    enums: set[str],
    value_records: set[str] | None = None,
) -> str | None:
    t = _clean_type(qualtype)
    ctype = _array_ctype(t, records, enums, value_records=value_records)
    if ctype is not None:
        return ctype
    ctype = _pointer_ctype(t, records, enums)
    if ctype is not None:
        return ctype
    if t in CTYPE_MAP:
        return CTYPE_MAP[t]
    if t in enums:
        return 'ctypes.c_int'
    if t in records:
        return t if value_records is None or t in value_records else None
    cls = _class_name_for_pointer(t, records)
    if cls:
        return f'ctypes.POINTER({cls})'
    return None


def generate(api: dict) -> tuple[str, list[str]]:
    records = {record['name'] for record in api.get('records', []) if record.get('name')}
    enums = {enum['name'] for enum in api.get('enums', []) if enum.get('name')}
    lines = [HEADER]

    for enum in api.get('enums', []):
        name = enum.get('name')
        if not name:
            continue
        lines.append(f'class {name}(CtypesEnum):\n')
        values = [value for value in enum.get('values', []) if value.get('name')]
        if values:
            for value in values:
                lines.append(f"    {value['name']} = {value.get('value', 0)}\n")
        else:
            lines.append('    pass\n')
        lines.append('\n\n')

    ordered_records = _ordered_records(api, records)
    layoutable_records = _layoutable_records(ordered_records, records, enums)

    for record in ordered_records:
        name = record.get('name')
        if not name:
            continue
        base = 'Union' if record.get('kind') == 'union' else 'Structure'
        lines.append(f'class {name}(ctypes.{base}):\n')
        lines.append('    pass\n\n\n')

    layout_records = []
    for record in ordered_records:
        name = record.get('name')
        if not name or record.get('opaque'):
            continue
        if name not in layoutable_records:
            continue
        fields = []
        for field in record.get('fields', []):
            field_name = field.get('name')
            if not field_name:
                break
            ctype = _ctype_for_type(
                field.get('type', {}), records, enums, value_records=layoutable_records
            )
            if ctype is None:
                break
            fields.append((field_name, ctype))
        else:
            lines.append(f'{name}._fields_ = [\n')
            for field_name, ctype in fields:
                lines.append(f"    ('{field_name}', {ctype}),\n")
            lines.append(']\n\n\n')
            layout_records.append(name)

    skipped = []
    emitted = []
    for function in api.get('functions', []):
        name = function['name']
        result = _ctype_for_type(
            function.get('result', {'qualtype': 'void'}),
            records,
            enums,
            value_records=layoutable_records,
        )
        argtypes = []
        for param in function.get('parameters', []):
            ctype = _ctype_for_type(
                param.get('type', {}), records, enums, value_records=layoutable_records
            )
            if ctype is None:
                break
            argtypes.append(ctype)
        else:
            if result is None:
                skipped.append(name)
                continue
            lines.append('try:\n')
            lines.append(f'    {name} = dvz.{name}\n')
            lines.append('except AttributeError:\n')
            lines.append(f"    _MISSING_FUNCTIONS.append('{name}')\n")
            lines.append('else:\n')
            if function.get('doc'):
                doc = function['doc'].replace('"""', "'''")
                lines.append(f'    {name}.__doc__ = """{doc}"""\n')
            lines.append(f'    {name}.argtypes = [{", ".join(argtypes)}]\n')
            lines.append(f'    {name}.restype = {result}\n')
            lines.append('\n\n')
            emitted.append(name)
            continue
        skipped.append(name)

    lines.append(f'_GENERATED_FUNCTION_COUNT = {len(emitted)}\n')
    lines.append(f'_SKIPPED_FUNCTIONS = {skipped!r}\n')
    lines.append(f'_DATOVIZ_CTYPES_LAYOUT_RECORDS = {layout_records!r}\n')
    lines.append("__all__ = [name for name in globals() if name.startswith(('dvz_', 'Dvz'))]\n")
    return ''.join(lines), skipped


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=DEFAULT_INPUT)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--check', action='store_true', help='fail if the generated file is stale')
    args = parser.parse_args()

    with args.input.open() as f:
        api = json.load(f)
    text, skipped = generate(api)

    if args.check:
        current = args.output.read_text() if args.output.exists() else ''
        if current != text:
            raise SystemExit(f'{args.output} is stale; run `just ctypes`')
        print(f'{args.output} is up to date ({len(skipped)} skipped functions)')
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)
    print(f'wrote {args.output} ({len(skipped)} skipped functions)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
